"""Cross-module contract tests for market-candle provenance and observation validation."""
from datetime import datetime, timezone
from unittest.mock import patch

import cin_public_market_candles_api as api
from cin_source_observation_contract import validate_source_observation


NOW = datetime(2026, 10, 28, 12, 0, tzinfo=timezone.utc)
CLOSED_ROWS = [
    {
        "open_time": 1793181600000 + i * 3_600_000,
        "open": 100 + i,
        "high": 103 + i,
        "low": 99 + i,
        "close": 102 + i,
        "volume": 10.0,
        "close_time": 1793185199999 + i * 3_600_000,
    }
    for i in range(5)
]


def _as_contract_observation(candle, envelope):
    metadata = candle["observation_metadata"]
    return {
        "source_id": metadata["source_id"],
        "subject": envelope["symbol"],
        "observed_at": metadata["observed_at"],
        "retrieved_at": metadata["retrieved_at"],
        "timestamp_semantics": metadata["timestamp_semantics"],
        "provenance": envelope["source_endpoint"],
        "quote_currency": metadata["quote_currency"],
        "interval": metadata["interval"],
    }


def test_endpoint_metadata_passes_source_observation_contract_without_claiming_freshness():
    # Use deterministic old candles; endpoint retrieval time is generated by the API.
    with patch.object(api, "_load", return_value=[
        {**row, "_source": "Coinbase Exchange public candles API (fallback after Binance HTTP 451)",
         "_source_endpoint": api.COINBASE_CANDLES_URL}
        for row in CLOSED_ROWS
    ]):
        envelope = api.get_market_candles
        import asyncio
        result = asyncio.run(envelope("BTCUSDT", "1h", 5))

    observation = _as_contract_observation(result["data"][0], result)
    validated = validate_source_observation(
        observation, now=datetime.now(timezone.utc)
    )
    assert validated["validity"] == "valid_metadata"
    assert validated["source_id"] == "coinbase_public"
    assert validated["quote_currency"] == "USD"
    assert validated["timestamp_semantics"] == "candle_close_time"
    assert validated["freshness_assessed"] is False
    assert validated["source_authenticity_verified"] is False


def test_forming_candle_open_time_semantics_is_accepted_but_not_called_fresh():
    metadata = api.candle_observation_metadata(
        source_id="binance_public",
        observed_at="2026-10-28T11:59:00+00:00",
        retrieved_at="2026-10-28T11:59:05+00:00",
        interval="1m",
        quote_currency="USDT",
        timestamp_semantics="candle_open_time",
    )
    observation = {
        "source_id": metadata["source_id"],
        "subject": "BTCUSDT",
        "observed_at": metadata["observed_at"],
        "retrieved_at": metadata["retrieved_at"],
        "timestamp_semantics": metadata["timestamp_semantics"],
        "provenance": "public-candles-endpoint",
        "quote_currency": metadata["quote_currency"],
        "interval": metadata["interval"],
    }
    validated = validate_source_observation(observation, now=NOW)
    assert validated["validity"] == "valid_metadata"
    assert validated["timestamp_semantics"] == "candle_open_time"
    assert validated["freshness_assessed"] is False


def test_invalid_quote_metadata_is_rejected_by_contract():
    observation = {
        "source_id": "coinbase_public",
        "subject": "BTCUSDT",
        "observed_at": "2026-10-28T11:59:00Z",
        "retrieved_at": "2026-10-28T11:59:05Z",
        "timestamp_semantics": "candle_close_time",
        "provenance": "public-candles-endpoint",
        "quote_currency": None,
        "interval": "1h",
    }
    result = validate_source_observation(observation, now=NOW)
    assert result["validity"] == "unknown"
    assert result["reason"] == "market_candle_quote_currency_required"
